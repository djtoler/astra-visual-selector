MATCH_CUT_MIN_MEDIA = 6

def is_match_cut(rec, pool_index=None):
    """True when a record can carry a sequence of sourced footage. Requires a
    capability record; a template that has never been measured is never claimed."""
    r = (pool_index or {}).get(rec.get("id")) or rec
    c = r.get("capability")
    if not c: return False
    return (c.get("carries") == ["identity"]
            and (c.get("media_slots") or 0) >= MATCH_CUT_MIN_MEDIA
            and c.get("staging") in ("reveals_in_turn", "all_at_once")
            and c.get("structure") in ("sequence", "list", "grid", "grouped_clusters"))

def match_cut_pool(pool_index):
    return [r for r in pool_index.values() if is_match_cut(r)]

