def _local(cap, content_class=None):
    """Templates that live on THIS side of the tree.

    approved-list.json is in Codex's tree and this side never writes it, so a template
    the user drops into ~/timeline/templates has no route into the pool at all. Same
    sidecar pattern capability.json already uses, for the same reason.

    A local record carries NO description and NO axes until a capability pass has
    watched its clip. A description written from a contact sheet is not evidence, and
    an unmeasured record must look unmeasured — `capability: None` is how the rest of
    the pipeline already says "nobody has asked".
    """
    import os
    if not os.path.exists(LOCAL): return []
    doc = _rj(LOCAL)
    out = []
    for r in doc.get("records") or []:
        rid = r["id"]
        # "*" admits every scope, exactly as the approved-list loop does. Without
        # it a LOCALLY registered scoped record could never load by any route — the
        # two timeline scenes were measured, in the sidecar, and invisible to
        # load(), load("timelines") and load("*") alike. The same gate-with-no-key
        # defect as LOG 0057, in the code path that fix did not touch.
        if content_class != "*" and \
           scope_of(rid, r.get("template")) not in (None, content_class): continue
        cp = cap.get(rid)
        # UNMEASURED means PENDING, not present. A record with no capability record
        # has no description either — Claude is not allowed to write one from a
        # contact sheet — and a record with no description cannot be judged by
        # PROMPT-bind, so admitting it would put an unjudgeable card in a slate.
        # local_pending() lists them so "not yet measured" never looks like "not there".
        if not cp: continue
