def is_spatial(rec):
    return rec.get("kind") in SPATIAL_KINDS

def needs_spatial(entity_count):
    """True when no flat template can credibly hold this many things."""
    return isinstance(entity_count, int) and entity_count > SPATIAL_MAX_SLOTS

def needs_long_carousel(entity_count):
    """True when a people roster should expose a capacity-qualified AE carousel."""
    return isinstance(entity_count, int) and entity_count >= LONG_CAROUSEL_MIN_PEOPLE

def is_long_media_carousel(rec, required_slots=LONG_CAROUSEL_MIN_PEOPLE):
    """Return whether an AE media carousel is measured to hold the full roster.

    The distinction is intentionally structural. A title containing ``carousel`` is
    not enough: the record must be an After Effects template, carry identity through
    media, reveal a sequence in turn, and report enough media and total slots. This
    excludes text-list carousels as well as spatial and infographic-system scenes.
    """
    if rec.get("kind") != "after_effects":
        return False
    if not isinstance(required_slots, int) or required_slots < LONG_CAROUSEL_MIN_PEOPLE:
        return False
    label = " ".join(str(rec.get(key) or "") for key in ("id", "template", "title")).lower()
    if "carousel" not in label:
        return False
    capability = rec.get("capability") or {}
    if capability.get("structure") != "sequence" or capability.get("staging") != "reveals_in_turn":
        return False
    if "identity" not in (capability.get("carries") or []):
        return False
    media_slots = capability.get("media_slots")
    total_slots = capability.get("slots_total")
    return (
        isinstance(media_slots, int)
        and isinstance(total_slots, int)
        and min(media_slots, total_slots) >= required_slots
    )

def _axis_base(k):
    return k.split("[")[0]

def unclassified_axes(recs):
    """Axis names in neither list. Preflight fails on these rather than guessing."""
    seen = set()
    for r in recs:
        for k in (r.get("axes") or {}):
            b = _axis_base(k)
            if b not in SUBJECT_AXES and b not in NON_SUBJECT_AXES: seen.add(b)
    return sorted(seen)

def subject_axes(rec):
    """Only the axes that count distinct things the scene is about.

    Raises on an unknown axis name. A new template introducing a new name must be
    classified by a human, not defaulted in either direction."""
    out = {}
    for k, v in (rec.get("axes") or {}).items():
        b = _axis_base(k)
        if b in SUBJECT_AXES:       out[k] = v
        elif b in NON_SUBJECT_AXES: continue
        else: raise ValueError(
            f"unclassified capacity axis {b!r} on {rec.get('id')!r} — add it to "
            f"SUBJECT_AXES or NON_SUBJECT_AXES in candidates.py, do not default it")
    return out

FEASIBLE = frozenset({"exact", "within", "unknown", "unlimited"})

def shape(recs, n):
    lo,hi=bounds(n); out=[]
    for r in recs:
        if is_spatial(r):
            out.append((r,"unlimited",[("unlimited",n)])); continue
        ax=subject_axes(r)
        hits=[(k,v) for k,v in ax.items() if lo<=v<=hi]
        if hits:
            exact=any(v==n for _,v in hits)
            out.append((r,"exact" if exact else "within", hits))
        elif not ax:
            # no SUBJECT axis declared. A record may declare metrics and csv_rows and
            # still say nothing about how many things it holds; that is unknown, not
            # outside. Missing capacity never disqualifies.
            out.append((r,"unknown",[]))
        else:
            out.append((r,"outside", sorted(ax.items(), key=lambda kv:abs(kv[1]-n))[:2]))
    return out


# Suffix shapes observed in the pool: --scene-N, --review-N, --review-vN-N, and those
# with a trailing letter (--review-Nb). A family is the id with that suffix removed.
_FAM_SUFFIX = re.compile(r"--(review|scene)(-v\d+)?-\d+[a-z]?$")

def _family(row):
    return _FAM_SUFFIX.sub("", row if isinstance(row, str) else row.get("id", ""))

def capacity_band(row, pool_index=None):
    """Coarse scale band, for display and audit only. Never disqualifies."""
    rec = (pool_index or {}).get(row.get("id")) or row
    ax = subject_axes(rec)          # not every axis: csv_rows 11 made a 2-subject
    if not ax: return "unknown"     # scene read as "several". See LOG 0013.
    n = max(ax.values())
    if n <= 1:  return "one"
    if n <= 4:  return "few"
    if n <= 12: return "several"
    return "many"

# ---------------------------------------------------------------------------
# Slate diversification
#
# One rule: a slate carries at most FAM_MAX scenes from any one template family.
# Family is the strongest available proxy for design language — two scenes from one
# pack share typography, motion and colour, so twelve of them is one choice wearing
# twelve hats.
#
# Mechanism clustering used to sit here as a second axis. It was removed 2026-09-20
# after measurement: its cap never fired on any job, and disabling it entirely changed
# 12 slate rows across 4 of 20 jobs. It was doing a tiebreak, at the cost of a whole
# subsystem, a review UI and an overrides file. See no-drifting LOG 0016.
# ---------------------------------------------------------------------------
FLOOD_PCT = 40      # over this share of the corpus, a job is not discriminating
FAM_MAX   = 1       # at most this many scenes from one template family in a slate
SLIDE_MAX = 3       # at most this many slideshow-ish entries before the slate must vary

# "We have seen enough slideshows" is taste, and taste is not locked to an exact name.
# These are CONTAINS stems against the template family, deliberately loose: a pack
# called "photo-slideshow-vertical-v3" should read as slide-ish without anyone
# updating a list. Loose matching is safe here because the consequence is only slate
# ORDER — a slide-ish record is never excluded from the pool, just pushed down the
# slate once three of its kind are already shown.
SLIDEISH_STEMS = ("slideshow", "photo", "carousel", "memories", "slides", "gallery")

def is_slideish(row):
    fam = _family(row).lower()
    return any(t in fam for t in SLIDEISH_STEMS)

def _within_family(r, pool_index=None):
    """Order scenes inside one family. Two real signals, then a stable arbitrary
    tiebreak — and the arbitrary part is named as such rather than pretending to rank.

      0a. how well its declared capacity fits the beat, when shotlist annotated it.
          A poor fit is not a defect — slots are re-cuttable (FACTS 2.7) — but a
          template that already holds the right number needs less work.
      0. a record the USER has already selected beats everything — their pick is the
         strongest evidence in the system, and a slate that stops showing what they
         chose is worse than one that does
      1. a binding the model judged `clear` beats one it judged `conditional`
      2. a record that declares a subject capacity beats one we know nothing about
      3. id, so the result is reproducible
    """
    FIT = {"exact": 0, "unlimited": 0, "footage": 0, "within": 1, "unknown": 2, "outside": 3}
    enc = r.get("_encfit", 0)
    fit = FIT.get(r.get("_capfit"), 2)
    # STAGE 2. `_rel` is a relevance score against this beat, set by the retrieval
    # index when one is loaded. Before it existed this slot was `id` — alphabetical —
    # which is the failure diagnosed on day one and never actually removed, only
    # buried under four other keys. Negated so higher similarity sorts first.
    rel = -(r.get("_rel") or 0.0)
    # A watchable clip outranks a still when everything else is equal. Last key before
    # the arbitrary one, so it never overrides fit, a user pick, or relevance.
    still = not has_motion(r, pool_index)
    picked = r["id"] not in _picked_ids()
    clear = ((r.get("provenance") or {}).get("verdict") != "clear")
    rec = (pool_index or {}).get(r.get("id")) or r
    try: declared = not subject_axes(rec)
    except ValueError: declared = True
    return (picked, enc, fit, clear, declared, rel, still, r["id"])

def diversify(rows, limit=12, corpus_size=None, pool_index=None,
              bound_families=None):
    """Return (slate, flooded, note).

    At most FAM_MAX scenes per template family, families visited rarest-first so an
    unusual pack is not crowded out by a large one. A slate shorter than `limit` means
    the library has that few families for this job; it is never padded.
    """
    flooded = corpus_size is not None and len(rows) * 100 / corpus_size > FLOOD_PCT

    fams = collections.defaultdict(list)
    for r in rows: fams[_family(r)].append(r)
    for f in fams: fams[f].sort(key=lambda r: _within_family(r, pool_index))
    # A family holding a record the user has already picked is visited FIRST. Rarest
    # -first is a reasonable default for families nobody has judged; it is not a reason
    # to drop a family the user has endorsed. Measured: on `enumerate` (249 bound, 12
    # families shown) two user-picked families fell outside the cut.
    picked = _picked_ids()
    FIT = {"exact": 0, "unlimited": 0, "footage": 0, "within": 1, "unknown": 2, "outside": 3}
    def bestfit(f): return min(FIT.get(r.get("_capfit"), 2) for r in fams[f])
    # ENCODING FIT OUTRANKS CAPACITY FIT. A slot count is re-cuttable and rendering
    # happens after selection (FACTS 2.6, 2.7, 3.6), so capacity is a hint about
    # scale. Whether a template can make the beat's relation VISIBLE is not
    # adjustable downstream — it is what the template does to data. Ranking scale
    # above meaning is how a slate full of correctly-sized slideshows was offered to
    # a beat that needed an aggregate.
    def bestenc(f): return min(r.get("_encfit", 0) for r in fams[f])
    # STAGE 2, at the level where it decides something. A family's relevance is its
    # BEST member's, because one member is what will represent it. Placed ahead of
    # family size and name: those are diversity heuristics for families nobody has
    # judged, and they were deciding the whole cut. `f` — the family NAME — was the
    # last word until 2026-09-21; that is the alphabetical fallback diagnosed on day
    # one, removed from _within_family and still living here one level up.
    def bestrel(f): return -max((r.get("_rel") or -1.0) for r in fams[f])
    # A family with no watchable clip sorts after one that has a clip, all else equal.
    # It must live HERE, not in _within_family: every still-only record is its own
    # family (46 records, 46 families, zero families with mixed motion), so the
    # within-family comparison never arises. Ranks, never excludes.
    def nomotion(f): return not any(has_motion(r, pool_index) for r in fams[f])
    # A record the USER NAMED FOR THIS BEAT sorts with the families they have
    # picked from, above every ranking signal. Beat 24's note was "the timeline
    # template clips, they absolutely should've been in here" — declaring the
    # content class admitted them and then the 10-slot cut dropped them again, so
    # the declaration achieved nothing. An admission is a statement that this
    # record belongs on this beat; it still competes WITHIN its family and still
    # earns its position among other named records, but it is not outranked by a
    # generic binding.
    NAMED = {"user-named", "scoped"}
    def named(f): return not any((r.get("provenance") or {}).get("verdict") in NAMED
                                 for r in fams[f])
    # NAMED BEATS PICKED, because named is about THIS beat and picked is global.
    # _picked_ids() is every record the user has ever selected anywhere — 61 after
    # pass 1, 103 after pass 2 — so as picks accumulate, "this family contains a
    # picked record" becomes true of most families and stops discriminating. On
    # beat 24 it outranked a timeline the user had explicitly declared for that
    # beat. A global signal must not outrank a beat-specific one.
    order = sorted(fams, key=lambda f: (named(f),
                                        not any(r["id"] in picked for r in fams[f]),
                                        bestenc(f), bestfit(f), bestrel(f),
                                        nomotion(f), len(fams[f]), f))

    slate, slid, deferred = [], 0, []
    for nth in range(FAM_MAX):            # one full pass per allowed scene per family
        for f in order:
            if len(slate) >= limit: break
            if len(fams[f]) <= nth: continue
            r = fams[f][nth]
            # A match-cut vessel is not "another slideshow" — it is its own
            # treatment, and the highest-acceptance one in the library (75% against
            # 30% overall). Carousels match the slide-ish stems, so without this the
            # cap spends its three slots on photo packs and withholds every vessel
            # behind them. Measured on beat 30a: 43 rows in, 4 out, all 17 match-cuts
            # dropped because three history-slideshow families filled the cap first.
            requested = ((r.get("provenance") or {}).get("verdict") == "match-cut"
                         or is_match_cut(r, pool_index))
            if is_slideish(r) and not requested:
                if slid >= SLIDE_MAX: deferred.append(r); continue
                slid += 1
            # THE REST OF THE FAMILY, carried on the chosen scene rather than
            # spending slate slots. FAM_MAX=1 was set after a slate came back 7 scenes
            # from one pack — the cap is right, but it hides 429 bound siblings across
            # 40 beats and the user has twice said "right family, wrong scene" with no
            # way to reach the sibling. Already ranked by _within_family, so [0] is the
            # shown one and the rest are in order.
            r["_siblings"] = [x["id"] for x in fams[f] if x["id"] != r["id"]]
            slate.append(r)
        if len(slate) >= limit: break
    # HARD cap. Past SLIDE_MAX the slate goes SHORT rather than filling with more of
    # the same — a fourth near-identical photo card is not a fourth choice, it is the
    # review time this cap exists to protect. The note says how many were withheld so
    # "short" is never read as "the library is empty".
    withheld = len(deferred)

    note = None
    if flooded or len(slate) < limit or withheld:
        bits = []
        if withheld:
            bits.append(f"{withheld} further slideshow-style scene(s) withheld past the "
                        f"cap of {SLIDE_MAX}; they are more of what is already shown.")
        if flooded:
            bits.append(f"{len(rows)} options, {len(rows)*100//(corpus_size or len(rows))}% "
                        f"of the corpus — this job is not discriminating.")
        bits.append(f"{len(rows)} candidate(s) here across {len(fams)} template "
                    f"families; showing {len(slate)}, at most {FAM_MAX} per family.")
        if len(slate) < limit:
            # REPORT THE OBSERVATION, NOT THE CAUSE. User ruling 2026-09-22: "we are
            # replicating taste and in the early stages, come stuff will not have an
            # answer just yet." LOG 0077.
            #
            # `rows` and `fams` are what reached diversify — AFTER
            # drop_prior_rejections. Counting them and calling the result a fact
            # about the library is how "the library has only 2 families" got printed
            # for a job bound across 8. LOG 0040 fixed the same sentence once by
            # checking len(fams) < limit; the check was right and the input was not.
            #
            # `bound_families` is the count BEFORE any beat-specific removal. Only
            # it can support a claim about the library, and only when nothing was
            # removed. Otherwise the note states what it saw and stops.
            if withheld:
                bits.append(f"Fewer than {limit}: the slideshow cap of {SLIDE_MAX} "
                            f"ended the slate.")
            elif bound_families is not None and bound_families > len(fams):
                bits.append(f"Fewer than {limit}: {bound_families} families are bound "
                            f"to this job, {len(fams)} reached this beat. The "
                            f"difference was removed earlier on this beat, not "
                            f"missing from the library.")
            elif bound_families is not None and bound_families <= limit:
                bits.append(f"Fewer than {limit}: {bound_families} families are bound "
                            f"to this job and all of them reached this beat.")
            else:
                bits.append(f"Fewer than {limit}; {len(fams)} families reached this "
                            f"beat.")
        note = " ".join(bits)
    return slate, flooded, note


