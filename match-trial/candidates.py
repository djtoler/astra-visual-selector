def apply_profile_corrections(recs, corr):
    """Apply `corr` to `recs` in place. Raises rather than failing quietly.

    A correction naming a record that is not in the pool, or a field the judgment
    never reads, is a mistake in the sidecar — a misspelled id, or a record later
    removed. Silence there is the recurring failure mode: the correction sits in
    the file looking applied and the wrong prose keeps shipping.
    """
    by_id = {r["id"]: r for r in recs}
    unknown = [k for k in corr if k not in by_id]
    if unknown:
        raise KeyError(f"profileCorrections names {len(unknown)} record(s) not in "
                       f"the pool: {', '.join(sorted(unknown))}")
    for rid, c in corr.items():
        bad = [f for f in c if not f.startswith("_") and f not in PROFILE_FIELDS]
        if bad:
            raise ValueError(f"profileCorrections[{rid}] sets {bad}; only "
                             f"{list(PROFILE_FIELDS)} are read by the judgment")
        for f in PROFILE_FIELDS:
            if f in c:
                by_id[rid][f] = c[f]
        by_id[rid].setdefault("sources", {})["profile"] = "user-correction"
    return recs

