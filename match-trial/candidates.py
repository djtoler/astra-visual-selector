def apply_capability_corrections(cap, corr):
    """`add` unions a list field. `set` replaces a SCALAR one.

    add-only could not express media_slots 0 -> 93. The four marker-plotting
    spatials measured 0 because the demo render showed bare markers; the two that
    already carried portraits measured media_slots == slots_at_once exactly, so
    the zeros are a property of the render and not the template (LOG 0086).

    `set` is deliberately a separate key and refuses list fields. An `add` can
    never delete a measurement; a `set` is an explicit scalar override the user
    has stated, and it stays out of capability.json so a re-ingest cannot bury
    it and a re-measure makes it reviewable.
    """
    for rid, c in corr.items():
        rec = cap.get(rid)
        for field, vals in (c.get("add") or {}).items():
            if rec is None: continue
            rec[field] = sorted(set(rec.get(field) or []) | set(vals))
        for field, val in (c.get("set") or {}).items():
            if isinstance(val, (list, tuple, set, dict)):
                raise ValueError(f"capabilityCorrections[{rid}].set.{field} is a "
                                 f"collection; `set` replaces scalars only, use `add`")
            if rec is None: continue
            rec[field] = val
        if rec is not None and c.get("why"):
            rec["userCorrected"] = c["why"]
    return cap

